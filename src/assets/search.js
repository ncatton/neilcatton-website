/* ═══════════════════════════════════════════════════════════════════
   Site-wide search — neilcatton.com

   Injects its overlay markup; the styling lives in site.css.

   Data sources
     /data/search-pages.json         — generated by build.mjs from the
                                       real page list, so it cannot drift
                                       (essays and Practice Library cards are pages
                                       on this site now, so Substack is not searched)

   Open   the Search link in the header, or Cmd/Ctrl+K
   Close  Escape or the close button
   Move   Arrow Up/Down through results, Enter to open the highlighted one

   Changes from the previous version, all from the August 2026 review:
     · the trigger is reachable on mobile (it used to live inside the
       desktop-only nav row and vanished with it below 580px)
     · multi-token scoring — "readiness AI" used to return nothing
       because matching was a single substring test
     · focus is trapped inside the dialog; aria-modal alone does not
       stop Tab reaching the page behind
     · result counts are announced, and the arrow-key highlight is
       exposed with aria-activedescendant
   ═══════════════════════════════════════════════════════════════════ */
(function () {
  "use strict";

  var STATIC_INDEX_URL = "/data/search-pages.json";
  var MAX_RESULTS      = 12;

  var allItems = [];
  var dataPromise = null;
  var activeIndex = -1;
  var lastTrigger = null;

  var SEARCH_ICON =
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ' +
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' +
    '<circle cx="11" cy="11" r="7"></circle><line x1="21" y1="21" x2="16.65" y2="16.65"></line></svg>';

  function esc(str) {
    var d = document.createElement("div");
    d.textContent = str == null ? "" : String(str);
    return d.innerHTML;
  }

  /* ── markup ───────────────────────────────────────────────────── */

  function bindTriggers() {
    /* Search in the header is a link to the sitemap, so it still goes somewhere with script off. */
    [].slice.call(document.querySelectorAll("[data-search]")).forEach(function (a) {
      a.addEventListener("click", function (e) {
        e.preventDefault();
        lastTrigger = a;
        openOverlay();
      });
    });
  }

  function injectOverlay() {
    var overlay = document.createElement("div");
    overlay.className = "search-overlay";
    overlay.id = "search-overlay";
    overlay.setAttribute("role", "dialog");
    overlay.setAttribute("aria-modal", "true");
    overlay.setAttribute("aria-label", "Site search");

    overlay.innerHTML =
      '<div class="search-panel">' +
        '<div class="search-top">' +
          '<label class="search-title" for="search-input">Search</label>' +
          '<button type="button" class="search-close-btn" id="search-close">Close</button>' +
        "</div>" +
        '<input type="search" class="search-input" id="search-input" autocomplete="off" ' +
          'role="combobox" aria-expanded="false" aria-controls="search-results" aria-autocomplete="list">' +
        '<div class="search-results" id="search-results" role="listbox" aria-label="Search results"></div>' +
        '<p class="visually-hidden" id="search-status" role="status" aria-live="polite"></p>' +
      "</div>";

    document.body.appendChild(overlay);

        document.getElementById("search-close").addEventListener("click", closeOverlay);

    var input = document.getElementById("search-input");
    var timer = null;
    input.addEventListener("input", function () {
      clearTimeout(timer);
      timer = setTimeout(function () { renderResults(input.value); }, 120);
    });

    input.addEventListener("keydown", function (e) {
      var items = document.getElementById("search-results").querySelectorAll(".search-result");
      if (e.key === "ArrowDown" && items.length) {
        e.preventDefault();
        activeIndex = Math.min(activeIndex + 1, items.length - 1);
        highlight(items);
      } else if (e.key === "ArrowUp" && items.length) {
        e.preventDefault();
        activeIndex = Math.max(activeIndex - 1, 0);
        highlight(items);
      } else if (e.key === "Enter" && activeIndex >= 0 && items[activeIndex]) {
        e.preventDefault();
        window.location.href = items[activeIndex].getAttribute("href");
      }
    });

    /* Focus trap. aria-modal="true" is a hint to assistive technology;
       it does not stop Tab reaching the document behind the dialog. */
    overlay.addEventListener("keydown", function (e) {
      if (e.key !== "Tab") return;
      var focusable = overlay.querySelectorAll('a[href], button, input, [tabindex]:not([tabindex="-1"])');
      if (!focusable.length) return;
      var first = focusable[0], last = focusable[focusable.length - 1];
      if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
    });
  }

  function highlight(items) {
    var input = document.getElementById("search-input");
    items.forEach(function (el, i) {
      var on = i === activeIndex;
      el.classList.toggle("active", on);
      el.setAttribute("aria-selected", on ? "true" : "false");
      if (on) {
        el.scrollIntoView({ block: "nearest" });
        input.setAttribute("aria-activedescendant", el.id);
      }
    });
  }

  /* ── data ─────────────────────────────────────────────────────── */

  function loadData() {
    if (dataPromise) return dataPromise;

    dataPromise = (function () {
      var pagesFetch = fetch(STATIC_INDEX_URL)
        .then(function (r) { return r.ok ? r.json() : { pages: [] }; })
        .catch(function () { return { pages: [] }; });

      return pagesFetch.then(function (res) {
        var typeOf = function (url) {
          if (url.indexOf("/writing/") === 0) return "Writing";
          if (url.indexOf("/practice-library/") === 0) return "Practice Library";
          return "Pages";
        };
        var order = { Pages: 0, Writing: 1, "Practice Library": 2 };
        allItems = (res.pages || []).map(function (p) {
          return { type: typeOf(p.url), title: p.title, url: p.url, excerpt: p.description || "" };
        }).sort(function (a, b) { return order[a.type] - order[b.type]; });
        return allItems;
      });
    })();

    return dataPromise;
  }

  /* ── scoring ──────────────────────────────────────────────────── */
  /* Every token has to appear somewhere in the title or the excerpt.
     Title matches outrank excerpt matches; an exact or prefix match
     on the whole phrase outranks both. */

  function scoreItem(item, tokens, phrase) {
    var title = (item.title || "").toLowerCase();
    var excerpt = (item.excerpt || "").toLowerCase();
    var hay = title + " " + excerpt;

    for (var i = 0; i < tokens.length; i++) {
      if (hay.indexOf(tokens[i]) === -1) return 0;
    }

    var score = 10;
    if (title === phrase) score += 100;
    else if (title.indexOf(phrase) === 0) score += 70;
    else if (title.indexOf(phrase) !== -1) score += 50;

    tokens.forEach(function (t) {
      if (title.indexOf(t) !== -1) score += 8;
      if (new RegExp("\\b" + t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).test(title)) score += 4;
    });

    return score;
  }

  function runSearch(query) {
    var phrase = query.trim().toLowerCase();
    if (!phrase) return [];
    var tokens = phrase.split(/\s+/).filter(Boolean);
    return allItems
      .map(function (item) { return { item: item, s: scoreItem(item, tokens, phrase) }; })
      .filter(function (x) { return x.s > 0; })
      .sort(function (a, b) { return b.s - a.s; })
      .slice(0, MAX_RESULTS)
      .map(function (x) { return x.item; });
  }

  function renderResults(query) {
    var resultsEl = document.getElementById("search-results");
    var statusEl  = document.getElementById("search-status");
    var input     = document.getElementById("search-input");
    activeIndex = -1;
    input.removeAttribute("aria-activedescendant");

    if (!query.trim()) {
      resultsEl.innerHTML = '<p class="search-hint">Pages, briefings and essays.</p><div class="search-try" role="group" aria-label="Suggested searches"><span>Try</span>' +
        ["readiness", "NHS", "board", "fraud"].map(function (w) { return '<button type="button" class="search-chip" data-q="' + w + '">' + w + "</button>"; }).join("") + "</div>";
      [].slice.call(resultsEl.querySelectorAll(".search-chip")).forEach(function (b) {
        b.addEventListener("click", function () { input.value = b.getAttribute("data-q"); input.focus(); renderResults(input.value); });
      });
      input.setAttribute("aria-expanded", "false");
      statusEl.textContent = "";
      return;
    }

    loadData().then(function () {
      var matches = runSearch(query);

      if (!matches.length) {
        resultsEl.innerHTML = '<div class="search-empty">No results for &ldquo;' + esc(query) + '&rdquo;.</div>';
        input.setAttribute("aria-expanded", "false");
        statusEl.textContent = "No results for " + query;
        return;
      }

      var html = "", currentType = null, n = 0;
      matches.forEach(function (item) {
        if (item.type !== currentType) {
          currentType = item.type;
          html += '<div class="search-section-label">' + esc(currentType) + "</div>";
        }
        html +=
          '<a class="search-result" role="option" aria-selected="false" id="search-result-' + n + '" href="' + esc(item.url) + '">' +
            '<div class="search-result-title">' + esc(item.title) + "</div>" +
            (item.excerpt ? '<div class="search-result-excerpt">' + esc(item.excerpt) + "</div>" : "") +
          "</a>";
        n++;
      });
      resultsEl.innerHTML = html;
      input.setAttribute("aria-expanded", "true");
      statusEl.textContent = matches.length + (matches.length === 1 ? " result" : " results") +
        " for " + query + ". Use the up and down arrow keys to review them.";
    });
  }

  /* ── open / close ─────────────────────────────────────────────── */

  function openOverlay() {
    var overlay = document.getElementById("search-overlay");
    overlay.classList.add("open");
    document.body.style.overflow = "hidden";
    loadData();
    var input = document.getElementById("search-input");
    input.value = "";
    renderResults("");
    setTimeout(function () { input.focus(); }, 30);
  }

  function closeOverlay() {
    var overlay = document.getElementById("search-overlay");
    overlay.classList.remove("open");
    document.body.style.overflow = "";
    if (lastTrigger) lastTrigger.focus();
  }

  function isOpen() {
    var overlay = document.getElementById("search-overlay");
    return overlay && overlay.classList.contains("open");
  }

  document.addEventListener("keydown", function (e) {
    if (isOpen()) {
      if (e.key === "Escape") { e.stopPropagation(); closeOverlay(); }
      return;
    }
        
    if ((e.key === "k" || e.key === "K") && (e.metaKey || e.ctrlKey)) {
      e.preventDefault();
      lastTrigger = document.querySelector(".nv-main [data-search]");
      openOverlay();
    }
  }, true);

  function init() { bindTriggers(); injectOverlay(); }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
})();
